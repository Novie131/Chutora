#!/usr/bin/env python3
"""PreCompact／SessionEnd hook：純腳本寫「自動交接快照」，不用模型、不輸出任何東西給模型、永遠 exit 0。

寫到哪：專案有 claude-memory/ → claude-memory/handoff-auto.md；否則 ~/.claude/chutora/handoff/<專案id>.md。
不動 handoff.md（那是模型／使用者寫的）。第一行是 `<!-- time: YYYY-MM-DD HH:MM -->`，SessionStart 靠它帶一行指標。
內容：時間、分支與最近 3 個 commit、最近 5 則使用者提示（各截 200 字）、碰過的檔案、最新待辦；整份經 redact.py 遮罩。
沒有任何使用者提示（空對話）時不寫，免得蓋掉上一份有用的快照。

`snapshot.py --path`：只印目前專案既有快照的路徑（沒有就不印）。session-start.sh 在沒有 claude-memory/ 時用。
"""
import json, os, subprocess, sys, time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

PROMPTS = 5
PROMPT_CHARS = 200
FILES_MAX = 20
TODOS_MAX = 15
EDIT_TOOLS = ("Write", "Edit", "MultiEdit", "NotebookEdit")
LABELS = {
    "zh": dict(title="自動交接快照", note="（腳本自動產生，不經模型；詳細的交接筆記在 handoff.md）", branch="分支",
               commits="最近 commit", prompts="最近的使用者提示", files="碰過的檔案", todos="最新待辦", none="（無）"),
    "en": dict(title="Auto handoff snapshot", note="(generated by a script, no model involved; the curated note is handoff.md)",
               branch="Branch", commits="Recent commits", prompts="Recent user prompts", files="Files touched",
               todos="Latest todos", none="(none)"),
}


def project_dir(data):
    return os.path.abspath(os.environ.get("CLAUDE_PROJECT_DIR") or data.get("cwd") or os.getcwd())


def snapshot_path(data, create=False):
    """快照要放的路徑。"""
    import projectid
    pd = project_dir(data)
    mem = os.path.join(pd, "claude-memory")
    if os.path.isdir(mem):
        return os.path.join(mem, "handoff-auto.md")
    d = os.path.join(projectid.conf_dir(), "handoff")
    if create:
        os.makedirs(d, exist_ok=True)
    return os.path.join(d, projectid.project_id(pd) + ".md")


def git(args, cwd):
    try:
        r = subprocess.run(["git", "-C", cwd] + args, capture_output=True, text=True, timeout=3,
                           stdin=subprocess.DEVNULL)
        return r.stdout.strip() if r.returncode == 0 else ""
    except Exception:
        return ""


def read_transcript(tp):
    """回傳 (最近的真正提示文字 list, 碰過的檔案 list（依先後、去重）, 最新待辦 list)。"""
    import usage
    prompts, files, todos = [], [], []
    with open(tp, encoding="utf-8", errors="replace") as f:
        for line in f:
            try:
                d = json.loads(line)
            except ValueError:
                continue
            if not isinstance(d, dict):
                continue
            if usage.is_real_prompt(d):
                t = usage.prompt_text(d).strip()
                if t and not t.startswith("<"):  # <command-name>／<local-command-…> 這類系統包裝不算
                    prompts.append(t)
                continue
            m = d.get("message")
            if d.get("type") != "assistant" or d.get("isSidechain") or not isinstance(m, dict):
                continue
            c = m.get("content")
            if not isinstance(c, list):
                continue
            for b in c:
                if not isinstance(b, dict) or b.get("type") != "tool_use":
                    continue
                inp = b.get("input") if isinstance(b.get("input"), dict) else {}
                if b.get("name") in EDIT_TOOLS:
                    p = inp.get("file_path") or inp.get("notebook_path")
                    if isinstance(p, str) and p:
                        if p in files:
                            files.remove(p)
                        files.append(p)
                elif b.get("name") == "TodoWrite" and isinstance(inp.get("todos"), list):
                    todos = [t for t in inp["todos"] if isinstance(t, dict)]
    return prompts[-PROMPTS:], files[-FILES_MAX:], todos


def build(data, lng, now=None):
    """組出快照全文；沒有使用者提示回傳 None。"""
    tp = data.get("transcript_path")
    if not tp or not os.path.isfile(tp):
        return None
    prompts, files, todos = read_transcript(tp)
    if not prompts:
        return None
    L = LABELS[lng]
    pd = project_dir(data)
    stamp = time.strftime("%Y-%m-%d %H:%M", time.localtime(now))
    out = [f"<!-- time: {stamp} -->", f"# {L['title']}（{stamp}）", L["note"], ""]
    branch = git(["branch", "--show-current"], pd)
    commits = git(["log", "-3", "--pretty=format:%h %s"], pd)
    out.append(f"## {L['branch']}")
    out.append(branch or L["none"])
    out += ["", f"## {L['commits']}"]
    out += ["- " + c for c in commits.splitlines()] if commits else [L["none"]]
    out += ["", f"## {L['prompts']}"]
    for t in prompts:
        t = " ".join(t.split())
        out.append("- " + (t if len(t) <= PROMPT_CHARS else t[:PROMPT_CHARS - 1] + "…"))
    out += ["", f"## {L['files']}"]
    out += ["- " + p for p in files] if files else [L["none"]]
    out += ["", f"## {L['todos']}"]
    mark = {"completed": "[x]", "in_progress": "[~]"}
    rows = ["- %s %s" % (mark.get(t.get("status"), "[ ]"), " ".join(str(t.get("content") or t.get("subject") or "").split()))
            for t in todos[:TODOS_MAX]]
    out += rows if rows else [L["none"]]
    return "\n".join(out) + "\n"


def write(data, now=None):
    from compact import lang
    from redact import redact
    text = build(data, lang(), now)
    if text is None:
        return None
    p = snapshot_path(data, create=True)
    tmp = "%s.%d.tmp" % (p, os.getpid())
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(redact(text))
    os.replace(tmp, p)
    return p


def main():
    try:
        if "--path" in sys.argv[1:]:
            p = snapshot_path({})
            if os.path.isfile(p):
                print(p)
            return
        data = json.load(sys.stdin)
        if isinstance(data, dict):
            write(data)
    except BaseException:  # 任何錯誤都安靜結束（含 SystemExit 以外的所有例外）
        pass


if __name__ == "__main__":
    main()
    sys.exit(0)
